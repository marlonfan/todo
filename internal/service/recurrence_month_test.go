func TestGregorianMonthConstraintsAcrossFrequencies(t *testing.T) {
	loc := loadLocationOrUTC("America/New_York")
	anchor := time.Date(2026, 1, 1, 9, 0, 0, 0, loc)
	for _, tc := range []struct {
		name string
		rule models.RecurrenceRule
		want []string
	}{
		{"daily", models.RecurrenceRule{Freq: "daily", ByMonth: []int{3}, Count: 2}, []string{"2026-03-01 09:00 -0500", "2026-03-02 09:00 -0500"}},
		{"weekly", models.RecurrenceRule{Freq: "weekly", ByMonth: []int{3}, ByDay: []string{"MO"}, Count: 3}, []string{"2026-03-02 09:00 -0500", "2026-03-09 09:00 -0400", "2026-03-16 09:00 -0400"}},
		{"monthly ordinal", models.RecurrenceRule{Freq: "monthly", ByMonth: []int{3, 11}, ByDay: []string{"2SU"}, Count: 3}, []string{"2026-03-08 09:00 -0400", "2026-11-08 09:00 -0500", "2027-03-14 09:00 -0400"}},
		{"yearly dates", models.RecurrenceRule{Freq: "yearly", ByMonth: []int{3, 11}, ByDate: []int{15}, Count: 3}, []string{"2026-03-15 09:00 -0400", "2026-11-15 09:00 -0500", "2027-03-15 09:00 -0400"}},
		{"missing month days", models.RecurrenceRule{Freq: "monthly", ByMonth: []int{2, 3}, ByDate: []int{31}, Count: 2}, []string{"2026-03-31 09:00 -0400", "2027-03-31 09:00 -0400"}},
		{"interval and month intersection", models.RecurrenceRule{Freq: "monthly", Interval: 2, ByMonth: []int{2, 3, 11}, ByDate: []int{1}, Count: 3}, []string{"2026-03-01 09:00 -0500", "2026-11-01 09:00 -0500", "2027-03-01 09:00 -0500"}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			task := &models.Task{StartTime: &anchor, RecurrenceRule: &tc.rule}
			got := buildTaskOccurrenceStarts(task, anchor, anchor.AddDate(3, 0, 0), loc.String())
			formatted := make([]string, len(got))
			for i, value := range got {
				formatted[i] = value.In(loc).Format("2006-01-02 15:04 -0700")
			}
			if !reflect.DeepEqual(formatted, tc.want) {
				t.Fatalf("month-constrained expansion = %v, want %v", formatted, tc.want)
			}
		})
	}
}

func TestCalendarMonthConstraintRoundtripWithMovedInstance(t *testing.T) {
	s, repo, userID := newTestTaskService(t)
	user, _ := s.userRepo.GetByID(userID)
	user.Timezone = "America/New_York"
	if err := s.userRepo.Update(user); err != nil {
		t.Fatal(err)
	}
	loc := loadLocationOrUTC(user.Timezone)
	start := time.Date(2026, 3, 8, 9, 0, 0, 0, loc)
	end := start.Add(time.Hour)
	task, err := s.Create(userID, &models.CreateTaskRequest{Title: "限定月份例会", StartTime: &start, EndTime: &end, RecurrenceRule: &models.RecurrenceRule{Freq: "monthly", ByMonth: []int{3, 11}, ByDay: []string{"2SU"}, Count: 3}})
	if err != nil {
		t.Fatal(err)
	}
	moved := time.Date(2026, 7, 1, 10, 0, 0, 0, loc)
	if _, err := s.UpdateOccurrenceSchedule(userID, task.ID, &models.UpdateTaskOccurrenceScheduleRequest{OccurrenceDate: "2026-11-08", StartTime: &moved}, nil, nil); err != nil {
		t.Fatal(err)
	}
	export := NewCalendarExportService(s, s.userRepo, "test")
	object, err := export.GetObject(userID, taskCalDAVHref(task))
	if err != nil || !strings.Contains(object.Data, "BYMONTH=3,11") {
		t.Fatal("export dropped the month constraint", object, err)
	}
	saveCalendarFixture(t, "month-constrained.ics", object.Data)
	again, created, err := export.UpsertObjectConditional(userID, object.Href, []byte(object.Data), object.ETag, "")
	if err != nil || created {
		t.Fatal("month-constrained GET/PUT roundtrip failed", err)
	}
	if !reflect.DeepEqual(again.Task.RecurrenceRule.ByMonth, []int{3, 11}) || again.Task.RecurrenceRule.Count != 3 {
		t.Fatal("roundtrip changed recurrence", again.Task.RecurrenceRule)
	}
	rows, err := repo.ListTaskOccurrences(userID, task.ID)
	if err != nil || len(rows) != 1 || !rows[0].StartTime.Equal(moved) {
		t.Fatal("roundtrip lost moved occurrence", rows, err)
	}
	// An exception may move outside the allowed month, but its identity must
	// still refer to a slot actually generated by the constrained series.
	bad := strings.Replace(again.Data, "RECURRENCE-ID;TZID=America/New_York:20261108T090000", "RECURRENCE-ID;TZID=America/New_York:20261011T090000", 1)
	if _, _, err := export.UpsertObject(userID, object.Href, []byte(bad)); err == nil {
		t.Fatal("accepted an identity outside the allowed months")
	}
	after, err := export.GetObject(userID, object.Href)
	if err != nil || after.ETag != again.ETag {
		t.Fatal("rejected exception modified the series", err)
	}
	// A real client can deliberately replace the month set in a later PUT.
	changed := strings.Replace(string(importCalendarDocument(importCalendarEvent(object.UID, "SUMMARY:新月份\nDTSTART;TZID=America/New_York:20260412T090000\nRRULE:FREQ=MONTHLY;BYMONTH=4,10;BYDAY=2SU;COUNT=2"))), "新月份", "已修改月份", 1)
	updated, _, err := export.UpsertObject(userID, object.Href, []byte(changed))
	if err != nil || !reflect.DeepEqual(updated.Task.RecurrenceRule.ByMonth, []int{4, 10}) {
		t.Fatal("month-set update failed", err)
	}
}
